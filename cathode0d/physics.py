"""Физические константы и замыкающие соотношения модели (уравнения 3-8, 11-18 статьи).

Все функции векторизованы: принимают скаляры или numpy-массивы одинаковой формы.
Единицы — СИ, кроме электронной температуры ``Te``, которая везде задаётся в эВ
(в формулах статьи она всегда встречается в комбинации k_B*T_e/q, т.е. в эВ).
"""
import numpy as np

# --- Фундаментальные константы -------------------------------------------
Q = 1.602176634e-19        # элементарный заряд, Кл
KB = 1.380649e-23          # постоянная Больцмана, Дж/К
ME = 9.1093837015e-31      # масса электрона, кг
EPS0 = 8.8541878128e-12    # электрическая постоянная, Ф/м
AMU = 1.66053906660e-27    # атомная единица массы, кг
EV_TO_K = Q / KB           # 1 эВ = 11604.5 К

# --- Ксенон --------------------------------------------------------------
XE_MASS = 131.293 * AMU          # масса атома/иона, кг
XE_EPS_I = 12.12                 # средняя энергия ионизации <eps_i>, эВ (из списка символов статьи)
XE_RG = KB / XE_MASS             # удельная газовая постоянная, Дж/(кг*К)
XE_GAMMA = 5.0 / 3.0             # показатель адиабаты одноатомного газа

# Коэффициенты фита усреднённого по Максвеллу упругого сечения e-Xe (ур. 8, таблица)
_P = (0.0350, -0.3057, -0.6698, -18.5416, -12.8821, -9.9614)
_Q = (0.7093, 0.5227)


def sigma_en(Te):
    """Сечение упругих e-n столкновений для Xe, м^2 (ур. 8). Te в эВ."""
    t = np.log10(Te)
    num = _P[0]*t**5 + _P[1]*t**4 + _P[2]*t**3 + _P[3]*t**2 + _P[4]*t + _P[5]
    den = t**2 + _Q[0]*t + _Q[1]
    return 10.0 ** (num / den)


def electron_mean_speed(Te):
    """Средняя тепловая скорость электронов sqrt(8kTe/(pi*me)), м/с."""
    return np.sqrt(8.0 * Q * Te / (np.pi * ME))


def ionization_rate(Te):
    """Коэффициент скорости ионизации Xe K_i, м^3/с.

    В статье формула не приведена; используется стандартный фит Гёбеля и Каца
    (Fundamentals of Electric Propulsion, ссылка [1] статьи):
    sigma_i = 1e-20*(3.97 + 0.643 Te - 0.0368 Te^2)*exp(-12.127/Te), K_i = sigma_i*<v_e>.
    """
    sig = 1e-20 * (3.97 + 0.643*Te - 0.0368*Te**2) * np.exp(-12.127 / Te)
    return sig * electron_mean_speed(Te)


def coulomb_log(ne, Te):
    """Кулоновский логарифм (ур. 7)."""
    return 23.0 - 0.5 * np.log(1e-6 * ne / Te**3)


def nu_ei(ne, Te):
    """Частота электрон-ионных столкновений, 1/с (ур. 5)."""
    return 2.9e-12 * ne * coulomb_log(ne, Te) / Te**1.5


def nu_en(nn, Te):
    """Частота электрон-нейтральных столкновений, 1/с (ур. 6).

    В статье множитель записан как (k_B T_e / n_e) — это явная опечатка (размерность
    не сходится). Используется стандартная форма <sigma_en> n_n <v_e>.
    """
    return sigma_en(Te) * nn * electron_mean_speed(Te)


def resistivity(ne, nn, Te):
    """Удельное сопротивление плазмы eta, Ом*м (ур. 4)."""
    return (nu_ei(ne, Te) + nu_en(nn, Te)) * ME / (ne * Q**2)


def xe_viscosity(T):
    """Вязкость ксенона, Па*с (ур. 12, формула Гёбеля-Каца, справедлива при T > 289.7 К)."""
    Tr = T / 289.7
    return 2.3e-5 * Tr ** (0.71 + 0.29 / Tr)


def j_bohm(ne, Te):
    """Плотность ионного тока Бома j_i, А/м^2 (ур. 13)."""
    return 0.61 * Q * ne * np.sqrt(Q * Te / XE_MASS)


def j_thermal(ne, Te):
    """'Тепловая' плотность тока j_th, А/м^2 (ур. 14, с массой иона, как в статье)."""
    return 0.25 * Q * ne * np.sqrt(8.0 * Q * Te / (np.pi * XE_MASS))


def sheath_field(ne, Te, Vp):
    """Электрическое поле у поверхности эмиттера E_c, В/м (ур. 17)."""
    bracket = 2.0 * np.sqrt(1.0 + 2.0 * Vp / Te) - 4.0
    bracket = np.maximum(bracket, 0.0)  # при малых Vp/Te поле не может быть мнимым
    return np.sqrt(ne * Q * Te / EPS0) * np.sqrt(bracket)


def j_emission(Ts, phi0, D, ne, Te, Vp):
    """Термоэмиссия Ричардсона-Дэшмана с эффектом Шоттки, А/м^2 (ур. 15-16)."""
    Ec = sheath_field(ne, Te, Vp)
    phi_eff = phi0 - np.sqrt(Q * Ec / (4.0 * np.pi * EPS0))
    return D * Ts**2 * np.exp(-Q * phi_eff / (KB * Ts))


def j_backstream(ne, Te, Vp):
    """Ток плазменных электронов, преодолевающих слой и уходящих на эмиттер, А/м^2 (ур. 18).

    В статье в экспоненте стоит k_B*T_s; физически барьер преодолевают электроны
    плазмы с температурой T_e (так у Альбертони [6] и Гёбеля [1]), поэтому здесь
    используется T_e. С T_s ~ 0.15 эВ этот член был бы пренебрежимо мал.
    """
    return 0.25 * Q * ne * np.exp(-Vp / Te) * electron_mean_speed(Te)


def double_sheath_voltage(Id, Te_o, ne_o, r_o):
    """Падение потенциала в двойном слое на входе в диафрагму V_ds, В (ур. 11)."""
    base = 9.0 * Id * Q * Te_o / (7.5 * np.pi * ne_o * r_o**2 * Q**2) * np.sqrt(ME / (2.0 * Q))
    return base ** (2.0 / 3.0)


def choked_total_density(mdot, area, Tw, ne, Te):
    """Полная плотность n_e + n_n из уравнения состояния в запертом сопле (ур. 1c/2c).

    (n_e+n_n) k Tw (1 + a Te/Tw) = mdot/A * sqrt(Rg Tw/gamma * (1 + a Te/Tw)),
    a = n_e/(n_e+n_n). Обозначив N = n_e+n_n и C = mdot/A*sqrt(Rg Tw/gamma)/(k Tw),
    получаем квадратное уравнение N^2 + N*(n_e Te/Tw) - C^2 = 0.
    """
    TeK = Te * EV_TO_K
    C = mdot / area * np.sqrt(XE_RG * Tw / XE_GAMMA) / (KB * Tw)
    b = ne * TeK / Tw
    return 0.5 * (-b + np.sqrt(b**2 + 4.0 * C**2))
